"""Regenerate data/vi_lexicon.txt (word/phrase lexicon used by the normalizer).

Sources: canonical phrases of data/teencode_dict.json, data/vi_business_words.txt, and the
question vocabulary (1-3 word n-grams) of the synthetic generator templates. The synth
files are only *read as text* here at build time; src/datamate never imports synth.

Usage: python scripts/build_lexicon.py [--check]
"""
from __future__ import annotations

import argparse
import ast
import json
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# Generated by scripts/build_lexicon.py - do not edit; edit data/vi_business_words.txt instead.\n"


def nfc(text: str) -> str:
    return unicodedata.normalize("NFC", text).strip().lower()


def template_questions(path: Path) -> list[str]:
    if not path.is_file():
        return []
    tree = ast.parse(path.read_text(encoding="utf-8"))
    return [node.value for node in ast.walk(tree)
            if isinstance(node, ast.Constant) and isinstance(node.value, str)
            and " " in node.value and node.value.rstrip().endswith(("?", "."))
            and any(ord(ch) > 127 for ch in node.value)]  # Vietnamese text only, not docstrings


def ngrams(sentence: str, longest: int = 4) -> set[str]:
    sentence = re.sub(r"\{[^}]*\}", " , ", sentence)
    entries: set[str] = set()
    for chunk in re.split(r"[^\w\s]|\d", sentence):
        words = [w for w in chunk.split() if w.isalpha()]
        for n in range(1, longest + 1):
            for i in range(len(words) - n + 1):
                entries.add(" ".join(words[i:i + n]))
    return entries


def build() -> list[str]:
    entries: set[str] = set()
    teencode = json.loads((ROOT / "data" / "teencode_dict.json").read_text(encoding="utf-8"))
    entries.update(nfc(k) for k in teencode)
    words = ROOT / "data" / "vi_business_words.txt"
    for line in words.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            entries.add(nfc(line))
    for sentence in template_questions(ROOT / "synth" / "src" / "questions.py"):
        entries.update(nfc(e) for e in ngrams(sentence))
    return sorted(e for e in entries if e)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if data/vi_lexicon.txt is stale")
    args = parser.parse_args()
    content = HEADER + "\n".join(build()) + "\n"
    target = ROOT / "data" / "vi_lexicon.txt"
    if args.check:
        return 0 if target.is_file() and target.read_text(encoding="utf-8") == content else 1
    target.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {target} ({content.count(chr(10)) - 1} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
